const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  listBooks: () => ipcRenderer.invoke('books:list'),
  bookStatus: (slug) => ipcRenderer.invoke('book:status', slug),
  pickPdf: () => ipcRenderer.invoke('pdf:pick'),
  pdfPage: (slug, page) => ipcRenderer.invoke('pdf:page', slug, page),
  run: (tabId, args) => ipcRenderer.invoke('proc:run', tabId, args),
  stop: () => ipcRenderer.invoke('proc:stop'),
  openPath: (p) => ipcRenderer.invoke('file:open', p),
  openEpubFolder: () => ipcRenderer.invoke('folder:epubs'),
  readStructure: (slug) => ipcRenderer.invoke('structure:read', slug),
  saveStructure: (slug, data) => ipcRenderer.invoke('structure:save', slug, data),
  saveToc: (slug, data) => ipcRenderer.invoke('structure:saveToc', slug, data),
  readParagraphs: (slug) => ipcRenderer.invoke('structure:paragraphs', slug),
  epubTemplates: () => ipcRenderer.invoke('epub:templates'),
  epubSummary: (slug) => ipcRenderer.invoke('epub:summary', slug),
  saveEpubAs: (file, name) => ipcRenderer.invoke('epub:saveAs', file, name),
  readEpub: (file) => ipcRenderer.invoke('epub:read', file),
  listMascots: () => ipcRenderer.invoke('mascots:list'),
  generateCover: (slug, opts) => ipcRenderer.invoke('cover:generate', slug, opts),
  readCover: (slug) => ipcRenderer.invoke('cover:read', slug),
  suggestCover: (slug, opts) => ipcRenderer.invoke('cover:suggest', slug, opts),
  analyzeCover: (slug, opts) => ipcRenderer.invoke('cover:analyze', slug, opts),
  readCloth: (slug) => ipcRenderer.invoke('cover:clothRead', slug),
  saveCloth: (slug, data) => ipcRenderer.invoke('cover:clothSave', slug, data),
  coverWrap: (slug) => ipcRenderer.invoke('cover:wrap', slug),
  listLibrary: () => ipcRenderer.invoke('library:list'),
  pickEpubs: () => ipcRenderer.invoke('library:pick'),
  addEpubs: (files) => ipcRenderer.invoke('library:add', files),
  removeEpub: (file) => ipcRenderer.invoke('library:remove', file),
  pathForFile: (f) => webUtils.getPathForFile(f),
  revealFile: (p) => ipcRenderer.invoke('file:reveal', p),
  ollamaStatus: () => ipcRenderer.invoke('ollama:status'),
  requiredModels: () => ipcRenderer.invoke('models:required'),
  modelState: (force) => ipcRenderer.invoke('models:state', force),
  setModels: (s) => ipcRenderer.invoke('models:set', s),
  sureTahmin: (slug, sina) => ipcRenderer.invoke('sure:tahmin', slug, sina),
  setScan: (s) => ipcRenderer.invoke('scan:set', s),
  onWinResized: (cb) => ipcRenderer.on('win:resized', () => cb()),
  onScanChanged: (cb) => ipcRenderer.on('scan:changed', (_e, d) => cb(d)),
  setupState: () => ipcRenderer.invoke('setup:state'),
  setupStartOllama: () => ipcRenderer.invoke('setup:startOllama'),
  setupInstallOllama: () => ipcRenderer.invoke('setup:installOllama'),
  setupDict: () => ipcRenderer.invoke('setup:dict'),
  setupPull: (models) => ipcRenderer.invoke('setup:pull', models),
  setupCancel: () => ipcRenderer.invoke('setup:cancel'),
  openDataDir: () => ipcRenderer.invoke('setup:openData'),
  openLink: (url) => ipcRenderer.invoke('setup:link', url),
  onSetupProgress: (cb) => ipcRenderer.on('setup:progress', (_e, d) => cb(d)),
  evalRef: (slug) => ipcRenderer.invoke('eval:ref', slug),
  bookSummary: (slug) => ipcRenderer.invoke('book:summary', slug),
  onLog: (cb) => ipcRenderer.on('proc:log', (_e, d) => cb(d)),
  onDone: (cb) => ipcRenderer.on('proc:done', (_e, d) => cb(d)),
});